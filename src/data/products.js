export function formatCurrency(value) {
  return new Intl.NumberFormat('pt-BR', {
    style: 'currency',
    currency: 'BRL',
  }).format(value);
}

export function formatWeight(kg) {
  return `${kg.toFixed(2).replace('.', ',')} kg`;
}
